export const GLYPH_W = 5;
export const GLYPH_H = 7;
const ADVANCE = 6; // 5 px glyph + 1 px spacing

export function normalizeText(text) {
  return String(text).normalize('NFD').replace(/\p{M}/gu, '').toUpperCase();
}

export function measureText(text, scale = 1) {
  const n = Array.from(normalizeText(text)).length;
  return n ? (n * ADVANCE - 1) * scale : 0;
}

// Draw directly with fillRect (fine for short HUD strings).
export function drawText(ctx, text, x, y, { color = '#fff', scale = 1, align = 'left', shadow = null } = {}) {
  const chars = Array.from(normalizeText(text));
  const w = measureText(text, scale);
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  if (shadow) drawGlyphs(ctx, chars, cx + scale, cy + scale, scale, shadow);
  drawGlyphs(ctx, chars, cx, cy, scale, color);
  return w;
}

function drawGlyphs(ctx, chars, x, y, scale, color) {
  ctx.fillStyle = color;
  for (const ch of chars) {
    const rows = G[ch] ?? G['?'];
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < GLYPH_W; c++) {
        if (bits & (0x10 >> c)) ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
      }
    }
    x += ADVANCE * scale;
  }
}

// Cached text sprite: render once to an offscreen canvas, blit every frame.
const cache = new Map();
export function textSprite(text, { color = '#fff', scale = 1, shadow = null } = {}) {
  const key = `${text}|${color}|${scale}|${shadow}`;
  let sprite = cache.get(key);
  if (!sprite) {
    const pad = shadow ? scale : 0;
    const c = document.createElement('canvas');
    c.width = Math.max(1, measureText(text, scale) + pad);
    c.height = GLYPH_H * scale + pad;
    drawText(c.getContext('2d'), text, 0, 0, { color, scale, shadow });
    sprite = c;
    if (cache.size > 300) cache.delete(cache.keys().next().value);
    cache.set(key, sprite);
  }
  return sprite;
}
